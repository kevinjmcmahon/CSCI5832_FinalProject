"""### Defining Dataset Object"""

import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader
from transformers import AutoTokenizer, AutoModelForSequenceClassification
from transformers import DataCollatorWithPadding


device = "cuda" if torch.cuda.is_available() else "cpu"

# IMPORTANT: set this to the base model you fine-tuned from
# e.g. "xlm-roberta-base" or "xlm-roberta-large"
BASE_MODEL_NAME = "xlm-roberta-base"  # <-- change if you used a different one

tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL_NAME)


class TextDataset(Dataset):
    def __init__(self, texts, tokenizer, max_length=128):
        self.texts = list(texts)
        self.tokenizer = tokenizer
        self.max_length = max_length

    def __len__(self):
        return len(self.texts)

    def __getitem__(self, idx):
        # Return plain dict; collator will turn into padded tensors
        enc = self.tokenizer(
            self.texts[idx],
            truncation=True,
            padding=False,      # no padding here, collator does it
            max_length=self.max_length,
        )
        return enc


def predict_logits(model_dir, texts, batch_size=32, max_length=128):
    """
    Load model from model_dir, run forward pass over texts, return logits (numpy).
    """
    print(f"\nLoading model from: {model_dir}")
    model = AutoModelForSequenceClassification.from_pretrained(model_dir)
    model.to(device)
    model.eval()

    ds = TextDataset(texts, tokenizer, max_length=max_length)

    # This is the key fix: collator pads input_ids/attention_mask per batch
    collator = DataCollatorWithPadding(tokenizer=tokenizer, return_tensors="pt")
    dl = DataLoader(ds, batch_size=batch_size, collate_fn=collator)

    all_logits = []
    with torch.no_grad():
        for batch in dl:
            batch = {k: v.to(device) for k, v in batch.items()}
            outputs = model(**batch)
            logits = outputs.logits  # shape: (B, num_labels)
            all_logits.append(logits.cpu().numpy())

    logits = np.concatenate(all_logits, axis=0)
    print("Logits shape:", logits.shape)
    return logits

"""### Helper to plot & save confusion matrices"""

import numpy as np

def plot_confusion_matrix(cm, classes, title, normalize=False, cmap=plt.cm.Blues):
    """
    cm: confusion matrix
    classes: list of class labels (e.g., [0, 1])
    title: string for the plot title
    normalize: whether to normalize rows
    """
    if normalize:
        cm = cm.astype("float") / cm.sum(axis=1, keepdims=True)

    fig, ax = plt.subplots(figsize=(4, 4))
    im = ax.imshow(cm, interpolation="nearest", cmap=cmap)
    ax.figure.colorbar(im, ax=ax)

    ax.set(
        xticks=np.arange(cm.shape[1]),
        yticks=np.arange(cm.shape[0]),
        xticklabels=classes,
        yticklabels=classes,
        ylabel="True label",
        xlabel="Predicted label",
    )

    # 🔥 Bold title here
    ax.set_title(title, fontweight="bold")

    fmt = ".2f" if normalize else "d"
    thresh = cm.max() / 2.0
    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            ax.text(
                j,
                i,
                format(cm[i, j], fmt),
                ha="center",
                va="center",
                color="white" if cm[i, j] > thresh else "black",
            )

    fig.tight_layout()
    return fig

"""### Defining Evaluation Metric"""

def logits_to_preds(logits, threshold=0.5):
    """
    Convert logits to integer labels.
    - If num_labels == 1: binary via sigmoid & threshold.
    - If num_labels >= 2: argmax over softmax.
    """
    if logits.ndim != 2:
        raise ValueError(f"Expected logits shape (N, C), got {logits.shape}")

    num_labels = logits.shape[1]

    if num_labels == 1:
        # Single-logit binary classification
        probs = 1.0 / (1.0 + np.exp(-logits[:, 0]))
        preds = (probs >= threshold).astype(int)
    else:
        # Multi-class classification (C >= 2)
        shifted = logits - logits.max(axis=1, keepdims=True)
        exp_logits = np.exp(shifted)
        probs = exp_logits / exp_logits.sum(axis=1, keepdims=True)
        preds = np.argmax(probs, axis=1)

    return preds

